import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { checkLaws } from './bend-laws.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const platforms = ['Android', 'Web', 'Windows', 'Posix'];
const requiredLaws = ['current_dir_is_inbe_everywhere', 'current_db_is_inbe',
    'legacy_dirs_differ_from_current', 'legacy_db_is_breathing',
    'export_entry_is_importable', 'historical_entries_stay_importable'];
const c = name => `main.${name}`;
const dirNames = { Inbe: 'inbe', Breathing: 'breathing',
    BreathSession: 'BreathSession' };
const dbNames = { InbeDb: 'inbe.db', BreathingDb: 'breathing.db' };
const entryNames = {
    InbeDataDb: 'inbe-data/inbe.db',
    BreathingDataDb: 'breathing-data/breathing.db',
};

export async function generateStorageLayout(packageDir, output,
    ziranOutput = output.replace(/\.h$/, '.zi')) {
    const proof = await checkLaws(path.join(packageDir, 'PROOF.bend'));
    assert.deepEqual(proof.laws.toSorted(), requiredLaws.toSorted(),
        'storage.layout.required_laws');

    const dirs = proof.table('main.current_dir');
    assert.deepEqual(dirs.domains, [platforms.map(c)],
        'storage.layout.current_dir_domain');
    assert.equal(dirs.rows.length, platforms.length,
        'storage.layout.current_dir_rows');
    const currentDirs = dirs.rows.map((row, index) => {
        assert.equal(row.arguments[0], c(platforms[index]),
            'storage.layout.current_dir_order');
        const constructor = row.value.constructor.slice('main.'.length);
        assert.ok(dirNames[constructor] !== undefined,
            'storage.layout.current_dir_name');
        return dirNames[constructor];
    });
    const olderDirs = proof.table('main.legacy_dir');
    assert.deepEqual(olderDirs.domains, [platforms.map(c)],
        'storage.layout.legacy_dir_domain');
    const legacyDirs = olderDirs.rows.map((row, index) => {
        assert.equal(row.arguments[0], c(platforms[index]),
            'storage.layout.legacy_dir_order');
        const constructor = row.value.constructor.slice('main.'.length);
        assert.ok(dirNames[constructor] !== undefined,
            'storage.layout.legacy_dir_name');
        return dirNames[constructor];
    });

    const scalar = (name, names) => {
        const result = proof.table(`main.${name}`);
        assert.deepEqual(result.domains, [], `storage.layout.${name}_domain`);
        assert.equal(result.rows.length, 1, `storage.layout.${name}_rows`);
        const constructor = result.rows[0].value.constructor.slice('main.'.length);
        assert.ok(names[constructor] !== undefined,
            `storage.layout.${name}_name`);
        return names[constructor];
    };
    const currentDb = scalar('current_db', dbNames);
    const legacyDb = scalar('legacy_db', dbNames);
    const exportEntry = scalar('export_entry', entryNames);
    const importable = proof.table('main.importable');
    assert.deepEqual(importable.domains, [Object.keys(entryNames).map(c)],
        'storage.layout.importable_domain');
    assert.equal(importable.rows.length, Object.keys(entryNames).length,
        'storage.layout.importable_rows');
    for (const row of importable.rows) {
        assert.equal(row.value.constructor, c('Yes'),
            'storage.layout.historical_entry_not_importable');
    }
    assert.equal(exportEntry, entryNames.InbeDataDb,
        'storage.layout.export_entry');
    assert.ok(currentDirs.every(name => name === dirNames.Inbe),
        'storage.layout.current_dir');
    assert.ok(legacyDirs.every((name, index) => name !== currentDirs[index]),
        'storage.layout.legacy_dir_distinct');

    const platformDefines = platforms.map((platform, index) =>
        `#define STORAGE_EXPECT_DIR_${platform.toUpperCase()} "${currentDirs[index]}"`).join('\n');
    const legacyDefines = platforms.map((platform, index) =>
        `#define STORAGE_DIR_LEGACY_${platform.toUpperCase()} "${legacyDirs[index]}"`).join('\n');
    const content = `/* Generated by scripts/generate-storage-layout.mjs from proved Bend ${proof.version} policy. */
#ifndef STORAGE_LAYOUT_H
#define STORAGE_LAYOUT_H

#define STORAGE_DIR_NAME "${dirNames.Inbe}"
#define STORAGE_DB_NAME "${currentDb}"
#define STORAGE_DB_NAME_LEGACY "${legacyDb}"
#define STORAGE_DIR_ARCHIVE_SUFFIX ".before-breathing-migration-"
#define STORAGE_EXPORT_ENTRY_DB "${exportEntry}"
#define STORAGE_EXPORT_ENTRY_META "inbe-data/metadata.json"
#define STORAGE_EXPORT_META_FORMAT "inbe-data-sqlite"
#define STORAGE_EXPORT_PREFIX "${dirNames.Inbe}"
#define STORAGE_IMPORT_ENTRY_COUNT ${Object.keys(entryNames).length}
static const char *const storage_import_entries[STORAGE_IMPORT_ENTRY_COUNT] = {
    "${exportEntry}",
    "${entryNames.BreathingDataDb}"
};
#define STORAGE_WEB_HOME "/home/${dirNames.Inbe}"
#define STORAGE_WEB_HOME_LEGACY "/home/${legacyDirs[1]}"
#define STORAGE_IMPORT_DB_TMP "import-${dirNames.Inbe}.db"
#define STORAGE_IMPORT_DB_INSPECT "import-inspect-${dirNames.Inbe}.db"
#define STORAGE_EXPORT_DB_TMP "export-${dirNames.Inbe}.db"
#define STORAGE_EXPORT_FILENAME_FMT "${dirNames.Inbe}-%lld.zip"
#define STORAGE_EXPORT_FILENAME_FALLBACK "${dirNames.Inbe}.zip"
#define STORAGE_EXPORT_SESSIONS_CSV "${dirNames.Inbe}-sessions.csv"
#define STORAGE_WEB_EXPORT_TMP "/tmp/${dirNames.Inbe}-web-export.zip"

${platformDefines}
${legacyDefines}
#if defined(__EMSCRIPTEN__) || defined(PLATFORM_WEB)
#define STORAGE_EXPECT_DIR_HERE STORAGE_EXPECT_DIR_WEB
#elif defined(ANDROID_BUILD)
#define STORAGE_EXPECT_DIR_HERE STORAGE_EXPECT_DIR_ANDROID
#elif defined(_WIN32)
#define STORAGE_EXPECT_DIR_HERE STORAGE_EXPECT_DIR_WINDOWS
#else
#define STORAGE_EXPECT_DIR_HERE STORAGE_EXPECT_DIR_POSIX
#endif
#endif
`;
    const ziran = `// Generated from the proved Bend storage layout. Do not edit by hand.
CurrentDirectoryName :: "${dirNames.Inbe}"
PreviousDirectoryPosix :: "${legacyDirs[3]}"
PreviousDirectoryWindows :: "${legacyDirs[2]}"
PreviousDirectoryAndroid :: "${legacyDirs[0]}"
PreviousDirectoryWeb :: "${legacyDirs[1]}"
ArchiveDirectorySuffix :: ".before-breathing-migration-"
CurrentDatabaseName :: "${currentDb}"
PreviousDatabaseName :: "${legacyDb}"
CurrentDatabaseEntry :: "${exportEntry}"
PreviousDatabaseEntry :: "${entryNames.BreathingDataDb}"
ExportMetadataEntry :: "inbe-data/metadata.json"
ExportMetadataFormat :: "inbe-data-sqlite"
ImportDatabaseTemporaryName :: "import-${dirNames.Inbe}.db"
InspectDatabaseTemporaryName :: "import-inspect-${dirNames.Inbe}.db"
ExportDatabaseTemporaryName :: "export-${dirNames.Inbe}.db"
ExportFilenameFormat :: "${dirNames.Inbe}-%lld.zip"
ExportFilenameFallback :: "${dirNames.Inbe}.zip"
ExportFilenamePrefix :: "${dirNames.Inbe}-"
ExportFilenameSuffix :: ".zip"
ExportSessionsCsv :: "${dirNames.Inbe}-sessions.csv"
CurrentWebHome :: "/home/${dirNames.Inbe}"
PreviousWebHome :: "/home/${legacyDirs[1]}"
WebExportTemporaryPath :: "/tmp/${dirNames.Inbe}-web-export.zip"
`;
    function writeIfChanged(destination, text) {
        fs.mkdirSync(path.dirname(destination), { recursive: true });
        if (fs.existsSync(destination) && fs.readFileSync(destination, 'utf8') === text)
            return;
        const temporary = `${destination}.${process.pid}.tmp`;
        try {
            fs.writeFileSync(temporary, text);
            fs.renameSync(temporary, destination);
        } finally {
            fs.rmSync(temporary, { force: true });
        }
    }
    writeIfChanged(output, content);
    writeIfChanged(ziranOutput, ziran);
    return proof;
}

if (process.argv[1] && pathToFileURL(path.resolve(process.argv[1])).href === import.meta.url) {
    try {
        assert.ok(process.argv.length <= 4,
            'usage: node scripts/generate-storage-layout.mjs [output.h] [output.zi]');
        const output = process.argv[2] ?? path.join(root, 'build/proofs/storage_layout.h');
        const ziranOutput = process.argv[3] ?? path.join(root, 'src/storage/storage_layout.zi');
        const proof = await generateStorageLayout(path.join(root, 'laws/storage_layout'),
            output, ziranOutput);
        console.log(`storage.layout: ${proof.laws.length} Bend laws proved; current layout generated`);
    } catch (error) {
        console.error(error.message);
        process.exitCode = 1;
    }
}
